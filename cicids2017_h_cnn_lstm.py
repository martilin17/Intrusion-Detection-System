def per_class_ovr(y_true, y_pred, n_classes):
    out = []
    N = len(y_true)
    for c in range(n_classes):
        tc = (y_true == c)
        pc = (y_pred == c)
        tp = int((tc & pc).sum())
        fn = int((tc & ~pc).sum())
        fp = int((~tc & pc).sum())
        tn = int((~tc & ~pc).sum())
        out.append(
            {
                "class_id": c,
                "DR": tp / (tp + fn + 1e-12),
                "ACC": (tp + tn) / (N + 1e-12),
                "FPR": fp / (fp + tn + 1e-12),
                "tp": tp,
                "fn": fn,
                "fp": fp,
                "tn": tn,
            }
        )
    return out


