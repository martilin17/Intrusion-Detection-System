def hierarchical_predict(bin_probs, atk_probs, gate_thr, joint_thr):
    p_attack = bin_probs[:, 1]
    atk_conf = atk_probs.max(axis=1)
    atk_pred = atk_probs.argmax(axis=1)  # 0..N_ATTACK-1
    joint = p_attack * atk_conf

    y_pred = np.zeros(len(p_attack), dtype=np.int64)  # default normal
    m = (p_attack >= gate_thr) & (joint >= joint_thr)
    y_pred[m] = atk_pred[m] + 1
    return y_pred, joint


def tune_thresholds(
    y_true_family,
    bin_probs,
    atk_probs,
    target_dr=0.90,
    target_fpr=0.03,
    gate_grid=np.linspace(0.10, 0.95, 86),
    joint_grid=np.linspace(0.10, 0.95, 86),
    topk=8,
):
    y_true_bin = (y_true_family != 0).astype(np.int64)

    cand = []
    best = None
    best_score = 1e18

    for g in gate_grid:
        for j in joint_grid:
            y_pred_family, _ = hierarchical_predict(bin_probs, atk_probs, float(g), float(j))
            y_pred_bin = (y_pred_family != 0).astype(np.int64)
            m = bin_metrics(y_true_bin, y_pred_bin)

            dr_under = max(0.0, target_dr - m["DR"])
            score = (1.8 * abs(m["FPR"] - target_fpr)) + (1.4 * abs(m["DR"] - target_dr)) + (6.0 * dr_under)

            cand.append((float(g), float(j), m, float(score)))
            if score < best_score:
                best_score = score
                best = (float(g), float(j), m, float(score))

    top = sorted(cand, key=lambda x: x[3])[:topk]

    print("\n[Hier Threshold Tuning on VAL (gate + joint)]")
    print(
        f"  chosen_gate_threshold={best[0]:.4f} | chosen_joint_threshold={best[1]:.4f} | "
        f"chosen_score={best[3]:.5f}"
    )
    print(
        f"  val_DR={best[2]['DR']*100:.2f}% | val_FPR={best[2]['FPR']*100:.2f}% | val_ACC={best[2]['ACC']*100:.2f}%"
    )
    print(f"  target_DR={target_dr*100:.2f}% | target_FPR={target_fpr*100:.2f}%")
    print("  top-threshold candidates:")
    for g, j, m, s in top:
        print(
            f"    g={g:.4f} | j={j:.4f} | score={s:.5f} | "
            f"DR={m['DR']*100:.2f}% | FPR={m['FPR']*100:.2f}% | ACC={m['ACC']*100:.2f}%"
        )
    return best[0], best[1]


