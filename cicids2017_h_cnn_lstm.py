    gate = load_gate_model(gate_json_path)
    atk, ckpt = load_attack_model(atk_pth_path, device)

    seq_len = int(cfg["seq_len"])
    gate_thr_local = float(cfg["gate_thr"])
    joint_thr_local = float(cfg["joint_thr"])
    feat_cols = list(ckpt["feature_cols"])
    scaler_min = np.asarray(ckpt["scaler_min_"], dtype=np.float32)
    scaler_scale = np.asarray(ckpt["scaler_scale_"], dtype=np.float32)

    xdf = df_new.copy()
    xdf.columns = xdf.columns.str.strip()
    for c in feat_cols:
        if c not in xdf.columns:
            xdf[c] = 0.0
    xdf = xdf[feat_cols]
    xdf = xdf.apply(pd.to_numeric, errors="coerce")
    X = xdf.to_numpy(dtype=np.float32)

    finite_mask = np.isfinite(X).all(axis=1)
    X = X[finite_mask]
    if len(X) < seq_len:
        raise ValueError(f"Not enough valid rows for sequence prediction: {len(X)} < seq_len={seq_len}")

    Xs = _scale_with_saved_state(X, scaler_min, scaler_scale).astype(np.float32)
    end_idx = np.arange(seq_len - 1, len(Xs), 1, dtype=np.int64)

    gate_probs = gate.predict_proba(Xs[end_idx])
    atk_probs = _collect_attack_probs_from_end_idx(atk, Xs, end_idx, seq_len, BATCH_T)

    y_pred_family, joint = hierarchical_predict(gate_probs, atk_probs, gate_thr_local, joint_thr_local)
    fam_names = cfg["family_names"]
    pred_names = [fam_names[i] for i in y_pred_family]

    out = pd.DataFrame(
        {
            "end_row_idx": end_idx,
            "pred_family_id": y_pred_family,
            "pred_family_name": pred_names,
            "p_attack": gate_probs[:, 1],
            "atk_conf": atk_probs.max(axis=1),
            "joint_score": joint,
        }
    )
    return out
