import torch
import torch.nn as nn

class CNNLSTMHybrid(nn.Module):
    def __init__(self, in_ch: int, n_classes: int, lstm_hidden=128, lstm_layers=2, bidir=True, dropout=0.5):
        super().__init__()
        self.block1 = nn.Sequential(
            nn.Conv1d(in_ch, 64, kernel_size=3, padding=1),
            nn.BatchNorm1d(64),
            nn.ReLU(),
            nn.MaxPool1d(2),
            nn.Dropout(dropout),
        )
        self.block2 = nn.Sequential(
            nn.Conv1d(64, 128, kernel_size=3, padding=1),
            nn.BatchNorm1d(128),
            nn.ReLU(),
            nn.MaxPool1d(2),
            nn.Dropout(dropout),
        )
        self.block3 = nn.Sequential(
            nn.Conv1d(128, 256, kernel_size=3, padding=1),
            nn.BatchNorm1d(256),
            nn.ReLU(),
            nn.MaxPool1d(2, ceil_mode=True),
            nn.Dropout(dropout),
        )

        self.bidir = bidir
        self.lstm = nn.LSTM(
            input_size=256,
            hidden_size=lstm_hidden,
            num_layers=lstm_layers,
            batch_first=True,
            dropout=dropout if lstm_layers > 1 else 0.0,
            bidirectional=bidir,
        )
        lstm_out = lstm_hidden * (2 if bidir else 1)

        self.fc = nn.Sequential(
            nn.Linear(lstm_out, 128),
            nn.BatchNorm1d(128),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(128, n_classes),
        )

    def forward(self, x):
        # x: (B, F, L)
        x = self.block1(x)
        x = self.block2(x)
        x = self.block3(x)          # (B, 256, L')
        x = x.transpose(1, 2)       # (B, L', 256)
        x, _ = self.lstm(x)         # (B, L', H)
        x = x[:, -1, :]             # last step
        return self.fc(x)

