def compute_class_weights(y: np.ndarray, n_classes: int, mode="sqrt", cap=None):
    c = np.bincount(y, minlength=n_classes).astype(np.float32)
    c = np.maximum(c, 1.0)
    if mode == "none":
        w = np.ones(n_classes, dtype=np.float32)
    elif mode == "linear":
        w = 1.0 / c
    else:
        w = np.sqrt(1.0 / c)
    if cap is not None:
        w = np.minimum(w, w.min() * cap)
    w = w / w.sum() * n_classes
    return torch.tensor(w, dtype=torch.float32), c.astype(np.int64)


@torch.no_grad()
def eval_loss(model, loader, criterion):
    model.eval()
    total, n = 0.0, 0
    for xb, yb in loader:
        xb, yb = xb.to(device), yb.to(device)
        loss = criterion(model(xb), yb)
        total += loss.item() * yb.size(0)
        n += yb.size(0)
    return total / max(1, n)


def train_attack_model(model, train_loader, val_loader, criterion, lr, epochs, patience):
    opt = torch.optim.Adam(model.parameters(), lr=lr)
    sch = torch.optim.lr_scheduler.CosineAnnealingLR(opt, T_max=epochs, eta_min=1e-5)

    best_state = None
    best_val = float("inf")
    wait = 0

    for ep in range(1, epochs + 1):
        model.train()
        total, n = 0.0, 0
        for xb, yb in train_loader:
            xb, yb = xb.to(device), yb.to(device)
            opt.zero_grad(set_to_none=True)
            loss = criterion(model(xb), yb)
            loss.backward()
            nn.utils.clip_grad_norm_(model.parameters(), GRAD_CLIP)
            opt.step()
            total += loss.item() * yb.size(0)
            n += yb.size(0)

        sch.step()
        tr = total / max(1, n)
        va = eval_loss(model, val_loader, criterion)
        is_best = va < best_val

        if is_best:
            best_val = va
            best_state = copy.deepcopy(model.state_dict())
            wait = 0
        else:
            wait += 1

        print(f"[ATK] ep={ep:02d} train={tr:.5f} val={va:.5f}" + (" *best" if is_best else ""))

        if wait >= patience:
            print(f"[ATK] early stop at ep={ep}, best_val={best_val:.5f}")
            break

    if best_state is not None:
        model.load_state_dict(best_state)
    return model, best_val


