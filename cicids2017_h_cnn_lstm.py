class WindowDataset(Dataset):
    def __init__(self, X: np.ndarray, end_idx: np.ndarray, y: np.ndarray, seq_len: int):
        self.X = X
        self.end_idx = end_idx.astype(np.int64)
        self.y = y.astype(np.int64)
        self.seq_len = int(seq_len)

    def __len__(self):
        return len(self.end_idx)

    def __getitem__(self, i):
        e = int(self.end_idx[i])
        s = e - self.seq_len + 1
        xw = self.X[s:e + 1]  # (L, F)
        return torch.from_numpy(xw).float().transpose(0, 1), torch.tensor(self.y[i], dtype=torch.long)


def make_loader_from_end_idx(X, end_idx, y, batch_size, shuffle):
    ds = WindowDataset(X, end_idx, y, SEQ_LEN)
    return DataLoader(
        ds,
        batch_size=batch_size,
        shuffle=shuffle,
        num_workers=NUM_WORKERS,
        pin_memory=PIN_MEMORY,
    )


def make_weighted_loader_from_end_idx(X, end_idx, y, batch_size):
    y = np.asarray(y, dtype=np.int64)
    n_classes = int(y.max()) + 1
    counts = np.bincount(y, minlength=n_classes).astype(np.float32)
    counts = np.maximum(counts, 1.0)
    class_w = 1.0 / np.sqrt(counts)
    sample_w = class_w[y]

    ds = WindowDataset(X, end_idx, y, SEQ_LEN)
    sampler = WeightedRandomSampler(
        weights=torch.from_numpy(sample_w).double(),
        num_samples=len(sample_w),
        replacement=True,
    )
    return DataLoader(
        ds,
        batch_size=batch_size,
        sampler=sampler,
        num_workers=NUM_WORKERS,
        pin_memory=PIN_MEMORY,
    )


