def _normalize_label(s: str) -> str:
    x = str(s).strip().lower().replace("_", " ").replace("-", " ")
    x = re.sub(r"[^a-z0-9\s]", " ", x)
    x = re.sub(r"\s+", " ", x).strip()
    return x


def _map_to_family(raw_label: str) -> str:
    x = _normalize_label(raw_label)
    if "benign" in x:
        return "Normal"
    # Check DDoS before DoS because "ddos" contains "dos".
    if "ddos" in x:
        return "DDoS"
    if ("dos" in x) or ("hulk" in x) or ("goldeneye" in x) or ("slowloris" in x) or ("slowhttptest" in x):
        return "DoS"
    if "patator" in x:
        return "BruteForce"
    if "web attack" in x or "sql injection" in x or "xss" in x:
        return "WebAttack"
    if "bot" in x:
        return "Botnet"
    if "portscan" in x or "port scan" in x:
        return "PortScan"
    # Explicitly excluded per experiment design.
    if "heartbleed" in x or "infiltration" in x:
        return "Unknown"
    return "Unknown"


def add_targets(df: pd.DataFrame, verbose: bool = True) -> pd.DataFrame:
    out = df.copy()
    out.columns = out.columns.str.strip()
    if "label" in out.columns and "Label" not in out.columns:
        out = out.rename(columns={"label": "Label"})
    if " Label" in out.columns and "Label" not in out.columns:
        out = out.rename(columns={" Label": "Label"})
    assert "Label" in out.columns, "No Label column found."

    out["Label_raw"] = out["Label"].astype(str)
    out["Family"] = out["Label_raw"].map(_map_to_family)

    unknown_n = int((out["Family"] == "Unknown").sum())
    if verbose and unknown_n > 0:
        print(f"[warn] drop unknown labels: {unknown_n}")
    out = out[out["Family"] != "Unknown"].reset_index(drop=True)

    out["y_bin"] = (out["Family"] != "Normal").astype(np.int64)
    out["y_family"] = out["Family"].map(FAMILY_TO_ID).astype(np.int64)

    out["y_attack7"] = np.int64(-1)
    m = out["Family"] != "Normal"
    out.loc[m, "y_attack7"] = out.loc[m, "Family"].map(ATTACK7_TO_ID).astype(np.int64)
    return out


def iter_cicids_chunks(csv_path: Path, chunksize: int):
    reader = pd.read_csv(
        csv_path,
        low_memory=False,
        chunksize=chunksize,
        nrows=CICIDS_NROWS_PER_FILE,
    )
    for ch in reader:
        ch.columns = ch.columns.str.strip()
        if "label" in ch.columns and "Label" not in ch.columns:
            ch = ch.rename(columns={"label": "Label"})
        if " Label" in ch.columns and "Label" not in ch.columns:
            ch = ch.rename(columns={" Label": "Label"})
        if "Label" not in ch.columns:
            continue
        if 0.0 < CICIDS_SAMPLE_FRAC_PER_FILE < 1.0:
            n_keep = max(1, int(len(ch) * CICIDS_SAMPLE_FRAC_PER_FILE))
            ch = ch.sample(n=n_keep, random_state=42)
        yield ch


def split_chunk_stratified(df_chunk: pd.DataFrame, rng: np.random.Generator):
    tr_parts, va_parts, te_parts = [], [], []
    for _, g in df_chunk.groupby("Family", sort=False):
        n = len(g)
        if n <= 2:
            tr_parts.append(g)
            continue
        idx = np.arange(n)
        rng.shuffle(idx)
        n_tr = int(round(n * 0.70))
        n_va = int(round(n * 0.15))
        n_tr = min(max(1, n_tr), n - 1)
        n_va = min(max(0, n_va), n - n_tr)
        n_te = n - n_tr - n_va
        if n_te < 0:
            n_te = 0
        g2 = g.iloc[idx]
        tr_parts.append(g2.iloc[:n_tr])
        if n_va > 0:
            va_parts.append(g2.iloc[n_tr:n_tr + n_va])
        if n_te > 0:
            te_parts.append(g2.iloc[n_tr + n_va:])
    df_tr = pd.concat(tr_parts, axis=0, ignore_index=True) if tr_parts else pd.DataFrame()
    df_va = pd.concat(va_parts, axis=0, ignore_index=True) if va_parts else pd.DataFrame()
    df_te = pd.concat(te_parts, axis=0, ignore_index=True) if te_parts else pd.DataFrame()
    return df_tr, df_va, df_te


def append_with_cap(df_base: pd.DataFrame, df_new: pd.DataFrame, cap: int):
    if df_new is None or len(df_new) == 0:
        return df_base
    if df_base is None or len(df_base) == 0:
        out = df_new
    else:
        out = pd.concat([df_base, df_new], axis=0, ignore_index=True)
    if (cap is not None) and (len(out) > cap):
        out = out.sample(n=cap, random_state=42).reset_index(drop=True)
    return out


